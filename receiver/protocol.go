package main

// Wire protocol between the ShakeLight phone app and this receiver (TCP, phone -> computer):
//
//	"SLC2"                                   4-byte magic, once, right after connecting
//	then packets: type(1) | length(4, BE) | pts in µs(8, BE) | payload(length)
//
// The receiver forwards the same packets unchanged to the browser page over /stream.
// Computer -> phone: type(1) | length(4, BE) | payload — a key-frame request or a JSON command.
const (
	magic    = "SLC2"
	oldMagic = "SLC1" // ShakeLight 1.1.0 on the phone (view only)

	pktHello  = 0   // payload: UTF-8 JSON {"name": "..."}
	pktConfig = 1   // payload: width(2, BE) | height(2, BE) | H.264 SPS+PPS (Annex B)
	pktKey    = 2   // payload: H.264 key frame (Annex B)
	pktDelta  = 3   // payload: H.264 frame (Annex B)
	pktAudio  = 4   // payload: PCM 16-bit little-endian, 48 kHz, stereo
	pktStatus = 5   // payload: JSON, what the computer may do (control, landscape…)
	pktApps   = 6   // payload: JSON list of the phone's apps with icons
	pktClip   = 7   // payload: UTF-8 text copied on the phone (Computer mode)
	pktBye    = 127 // generated by the receiver when the phone disconnects

	headerSize   = 13
	maxPacketLen = 16 << 20

	ctrlRequestKeyframe = 1
	ctrlCommand         = 2 // payload: one JSON command (see RemoteCommands.kt)
	ctrlWelcome         = 3 // payload: JSON {"version": "..."}, sent right after a phone connects
	maxCommandLen       = 1 << 20

	discoveryPort = 47800 // UDP: receiver announces itself on the local network
	streamPort    = 47801 // TCP: phone connects here
	webPort       = 47802 // HTTP on 127.0.0.1: the viewer page
)

func encodeControl(kind byte, payload []byte) []byte {
	out := make([]byte, 5+len(payload))
	out[0] = kind
	n := uint32(len(payload))
	out[1], out[2], out[3], out[4] = byte(n>>24), byte(n>>16), byte(n>>8), byte(n)
	copy(out[5:], payload)
	return out
}

func encodePacket(kind byte, pts int64, payload []byte) []byte {
	out := make([]byte, headerSize+len(payload))
	out[0] = kind
	n := uint32(len(payload))
	out[1], out[2], out[3], out[4] = byte(n>>24), byte(n>>16), byte(n>>8), byte(n)
	for i := 0; i < 8; i++ {
		out[5+i] = byte(pts >> (56 - 8*i))
	}
	copy(out[headerSize:], payload)
	return out
}
